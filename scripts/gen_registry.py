"""Writes the registries the page and the relay read the railroad plug-ins
(scripts/railroads/*.py) from:

    python3 scripts/gen_registry.py

js/railroads/index.js: each plug-in's railroads (AGENCIES, with a bbox from
data/stations.json where it has their stations, else the module's own), its
sources as stubs (no parser: js/railroads/<id>.js is imported the first time
one is polled), the loaders for those files, and RAIL_REGIONS (the regional
track files in data/rail/index.json, when there is one) and DATA_REGIONS
(the station and timetable files of railroads outside the US and Canada,
data/regions/<region>/, with their railroads and extent).

relay/feeds/index.js: each plug-in's relay feeds (RELAY), and for the ones
with no url, the custom fetchFeed in relay/feeds/<id>.js (whose Python twin
is the module's relay_fetch, for scripts/dev_relay.py).

Detail sources (DETAILS = {"<source id>": {"ttl": seconds}}): one train at a
time, fetched through the relay only when a viewer opens or tracks it, as
/feed/<source id>?train=<number>&date=<yyyy-mm-dd>[&from=<origin name>]. They
need relay_fetch(env, source_id, query) and its Worker twin, and a railroad
uses one by naming it in its AGENCIES entry ("detail": "<source id>"); the
answer has one shape for every source (js/sources.js applyDetail), so there
is no parser. A module may define DETAILS alone, with no AGENCIES, SOURCES,
GTFS, RAIL or RELAY (a relay-only plug-in, e.g. viaggiatreno.py, which
serves railroads defined in other plug-ins).

The output is sorted and formatted the same way every time, so running it
again changes nothing.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from railroads import load  # noqa: E402
from feeds import REGION, read_split  # noqa: E402

KINDS = {"commuter", "intercity"}
SCOPES = {"view", "always"}
FORMATS = {"pb", "json", "xml", "text", "timetable"}  # "timetable": no feed, trains placed from the GTFS
HEAD = "// Generated by scripts/gen_registry.py from scripts/railroads/*.py: edit those and run it again.\n"


def js(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(", ", ": "))


def fail(mod, msg):
    sys.exit(f"scripts/railroads/{mod}.py: {msg}")


def station_boxes():
    """Each railroad's stations' extent, [west, south, east, north] (the
    regions' stations too)."""
    boxes = {}
    for agency, rows in read_split("stations.json").items():
        pts = [(r[3], r[2]) for r in rows if isinstance(r[2], (int, float)) and isinstance(r[3], (int, float))]
        if pts:
            boxes[agency] = [round(min(p[0] for p in pts), 3), round(min(p[1] for p in pts), 3),
                             round(max(p[0] for p in pts), 3), round(max(p[1] for p in pts), 3)]
    return boxes


def rail_regions():
    path = ROOT / "data" / "rail" / "index.json"
    return sorted(json.loads(path.read_text()), key=lambda r: r["region"]) if path.exists() else []


# The files of data/regions/<region>/ (feeds.write_split), as the page names them.
KINDS_OF_DATA = ("stations", "departures", "firsts", "linecolors", "trips")


def data_regions(agencies):
    """Each region's station and timetable files (data/regions/<region>/):
    its railroads, the files it has, and its extent, all its railroads'."""
    out = []
    for region in sorted(set(REGION.values())):
        files = [k for k in KINDS_OF_DATA if (ROOT / "data" / "regions" / region / f"{k}.json").exists()]
        boxes = [agencies[a]["bbox"] for a in sorted(REGION) if REGION[a] == region and agencies.get(a, {}).get("bbox")]
        if files and boxes:
            out.append({"region": region, "agencies": sorted(a for a in REGION if REGION[a] == region and a in agencies), "files": files,
                        "bbox": [min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes)]})
    return out


def main():
    boxes = station_boxes()
    agencies, sources, loaders, feeds, imports = {}, [], {}, {}, {}
    details, wants = {}, {}  # detail source id -> its plug-in; agency -> (plug-in, the detail source it names)
    for mod in load():
        mid = mod.__name__.split(".")[-1]
        if not re.fullmatch(r"[a-z0-9]+", mid):
            fail(mid, "plug-in ids are lowercase letters and digits")
        for did, d in getattr(mod, "DETAILS", {}).items():
            if not re.fullmatch(r"[a-z0-9]+", did) or did in details or did in feeds or any(x["id"] == did for x in sources):
                fail(mid, f"detail source {did}: ids are lowercase letters and digits, unique among sources")
            if not hasattr(mod, "relay_fetch") or not (ROOT / "relay" / "feeds" / f"{mid}.js").exists():
                fail(mid, f"detail source {did} needs relay_fetch and its Worker twin, relay/feeds/{mid}.js")
            ttl = d.get("ttl", 15)
            if not isinstance(ttl, (int, float)) or isinstance(ttl, bool) or ttl <= 0:
                fail(mid, f"detail source {did}: ttl is seconds, a number > 0")
            details[did] = mid
            feeds[did] = {"detail": True, "format": "json", "ttl": ttl, "fetchFeed": mid}
            imports[mid] = True
        if not getattr(mod, "AGENCIES", None):
            # A relay-only plug-in: detail sources for other plug-ins' railroads.
            if getattr(mod, "DETAILS", None) and not any(getattr(mod, k, None) for k in ("SOURCES", "GTFS", "RAIL", "RELAY")):
                continue
            fail(mid, "no AGENCIES (only a plug-in with nothing but DETAILS may have none)")
        for aid, a in mod.AGENCIES.items():
            if aid in agencies:
                fail(mid, f"agency {aid} is already in another plug-in")
            for key in ("name", "short", "region", "country", "color", "kind"):
                if not a.get(key):
                    fail(mid, f"agency {aid} has no {key}")
            if a["kind"] not in KINDS or not re.fullmatch(r"#[0-9a-f]{6}", a["color"]) or not re.fullmatch(r"[A-Z]{2}", a["country"]):
                fail(mid, f"agency {aid}: kind, color (#rrggbb) or country (ISO 3166 alpha-2) is off")
            if "detail" in a:
                wants[aid] = (mid, a["detail"])
            box = boxes.get(aid) or a.get("bbox")
            # "clip": its stations abroad (a timetable's through trains to
            # Paris or Vienna) don't stretch its extent past its own box.
            if a.get("clip") and a.get("bbox") and box is not a["bbox"]:
                own = a["bbox"]
                box = [max(box[0], own[0]), max(box[1], own[1]), min(box[2], own[2]), min(box[3], own[3])]
            agencies[aid] = {**a, "bbox": box}
        relay = getattr(mod, "RELAY", {})
        custom = hasattr(mod, "relay_fetch")
        if custom and not (ROOT / "relay" / "feeds" / f"{mid}.js").exists():
            fail(mid, f"relay_fetch has no Worker twin, relay/feeds/{mid}.js")
        for s in getattr(mod, "SOURCES", []):
            sid = s["id"]
            if any(x["id"] == sid for x in sources) or sid in details:
                fail(mid, f"source {sid} is already in another plug-in")
            if not s.get("agencies") or any(x not in mod.AGENCIES for x in s["agencies"]):
                fail(mid, f"source {sid} names an agency it doesn't define")
            if s.get("format", "json") not in FORMATS or s.get("scope", "view") not in SCOPES:
                fail(mid, f"source {sid}: format or scope is off")
            if not isinstance(s.get("interval"), (int, float)) or isinstance(s["interval"], bool) or s["interval"] <= 0:
                fail(mid, f"source {sid} needs an interval, seconds between polls")
            if s.get("format") == "timetable":
                # A railroad with no live data: its trains are placed from its
                # own timetable, so it needs one and fetches nothing.
                if s.get("relay") or s.get("url"):
                    fail(mid, f"source {sid}: a timetable source fetches no feed (no relay, no url)")
                if any(a not in getattr(mod, "GTFS", {}) for a in s["agencies"]):
                    fail(mid, f"source {sid}: a timetable source needs GTFS for each of its agencies")
            first = mod.AGENCIES[s["agencies"][0]]
            stub = {k: v for k, v in s.items() if k in ("id", "agencies", "format", "interval", "relay", "needsKey", "url", "after")}
            stub.update(scope=s.get("scope", "view"), module=mid,
                        credit={**(first.get("credit") or {"label": first["name"], "href": ""}), "license": first.get("license")})
            sources.append(stub)
            if not s.get("relay"):
                continue
            spec = dict(relay.get(sid) or {})
            if spec.get("url"):
                feeds[sid] = {**spec, "format": s.get("format", "json")}
            elif custom:
                feeds[sid] = {**spec, "format": s.get("format", "json"), "fetchFeed": mid}
                imports[mid] = True
            else:
                fail(mid, f"relay source {sid} has neither a RELAY url nor relay_fetch")
        if (ROOT / "js" / "railroads" / f"{mid}.js").exists():
            loaders[mid] = True
        elif any(s.get("format") != "timetable" for s in getattr(mod, "SOURCES", [])):
            fail(mid, f"js/railroads/{mid}.js is missing: a source with a feed needs a parser")
    for aid, (mid, did) in sorted(wants.items()):
        if did not in details:
            fail(mid, f"agency {aid}: detail {did!r} is no plug-in's detail source (DETAILS)")

    out = [HEAD, "// The railroad plug-ins, as js/sources.js merges them into AGENCIES and SOURCES.\n\n",
           "export const AGENCIES = {\n"]
    out += [f"  {aid}: {js(agencies[aid])},\n" for aid in sorted(agencies)]
    out += ["};\n\n", "export const SOURCES = [\n"]
    out += [f"  {js(s)},\n" for s in sorted(sources, key=lambda s: s["id"])]
    out += ["];\n\n", "// Each plug-in's parsers (js/railroads/<id>.js), loaded the first time one of its sources is polled.\n",
            "export const PARSERS = {\n"]
    out += [f'  {mid}: () => import("./{mid}.js?v=dev"),\n' for mid in sorted(loaders)]
    out += ["};\n\n", "// The regional track files (data/rail/index.json).\n", "export const RAIL_REGIONS = [\n"]
    out += [f"  {js(r)},\n" for r in rail_regions()]
    out += ["];\n\n", "// Station and timetable data outside the US and Canada (data/regions/<region>/), by region.\n",
            "export const DATA_REGIONS = [\n"]
    out += [f"  {js(r)},\n" for r in data_regions(agencies)]
    out += ["];\n"]
    write(ROOT / "js" / "railroads" / "index.js", "".join(out))

    out = [HEAD, "// The railroad plug-ins' relay feeds, as relay/worker.js merges them into FEEDS. {NAME} in a url or\n",
           "// header is the Worker secret NAME; a feed whose keys aren't all set is off.\n"]
    out += [f'import {{ fetchFeed as {mid} }} from "./{mid}.js";\n' for mid in sorted(imports)]
    out += ["\nexport const FEEDS = {\n"]
    for sid in sorted(feeds):
        spec = dict(feeds[sid])
        hook = spec.pop("fetchFeed", None)
        body = js(spec)
        out.append(f"  {sid}: {body[:-1]}, \"fetchFeed\": {hook} }},\n" if hook else f"  {sid}: {body},\n")
    out += ["};\n"]
    write(ROOT / "relay" / "feeds" / "index.js", "".join(out))


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
